// Top-level integration skeleton for the Circuit Switchers direct-mapped cache.
//
// This module intentionally contains connection logic only. The storage,
// lookup, controller, and memory modules are owned by Members 02-04 and must
// implement the exact ports documented in docs/interface_contract.md.
//
// Initial scope: one outstanding read request, 8-bit response data, active-high
// synchronous reset, and a one-cycle resp_valid completion pulse.
module cache_top (
    input  wire        clk,
    input  wire        reset,

    // Processor/requester interface.
    input  wire        req_valid,
    input  wire [31:0] req_addr,
    output wire        req_ready,

    output wire        resp_valid,
    output wire [7:0]  resp_data,
    output wire        resp_hit
);

    // Combinational fields from the currently presented request address.
    wire [21:0] decoded_tag;
    wire [5:0]  decoded_index;
    wire [3:0]  decoded_offset;

    // Controller-held fields for the accepted request. These remain stable
    // throughout lookup, memory wait, refill, and response.
    wire [21:0] active_tag;
    wire [5:0]  active_index;
    wire [3:0]  active_offset;

    // Selected cache-line contents.
    wire [127:0] stored_block;
    wire [21:0]  stored_tag;
    wire         stored_valid;

    // Lookup and byte-selection results.
    wire         lookup_hit;
    wire [7:0]   cache_byte_data;
    wire [7:0]   refill_byte_data;

    // Refill controls generated by the controller.
    wire         refill_write_en;

    // Main-memory block-read interface.
    wire         mem_req;
    wire [31:0]  mem_addr;
    wire         mem_ready;
    wire [127:0] mem_block;

    // A memory refill always requests the aligned 16-byte block containing the
    // active address.
    assign mem_addr = {active_tag, active_index, 4'b0000};

    address_decoder u_address_decoder (
        .address(req_addr),
        .tag(decoded_tag),
        .index(decoded_index),
        .offset(decoded_offset)
    );

    cache_data_ram u_cache_data_ram (
        .clk(clk),
        .read_index(active_index),
        .read_block(stored_block),
        .write_en(refill_write_en),
        .write_index(active_index),
        .write_block(mem_block)
    );

    tag_ram u_tag_ram (
        .clk(clk),
        .read_index(active_index),
        .read_tag(stored_tag),
        .write_en(refill_write_en),
        .write_index(active_index),
        .write_tag(active_tag)
    );

    valid_bit_ram u_valid_bit_ram (
        .clk(clk),
        .reset(reset),
        .read_index(active_index),
        .read_valid(stored_valid),
        .write_en(refill_write_en),
        .write_index(active_index),
        .write_valid(1'b1)
    );

    cache_lookup u_cache_lookup (
        .requested_tag(active_tag),
        .stored_tag(stored_tag),
        .stored_valid(stored_valid),
        .hit(lookup_hit)
    );

    // Offset zero maps to block_data[7:0]. See the interface contract for the
    // complete byte-lane convention.
    data_selector u_cache_data_selector (
        .block_data(stored_block),
        .byte_offset(active_offset),
        .selected_byte(cache_byte_data)
    );

    data_selector u_refill_data_selector (
        .block_data(mem_block),
        .byte_offset(active_offset),
        .selected_byte(refill_byte_data)
    );

    cache_controller u_cache_controller (
        .clk(clk),
        .reset(reset),

        .req_valid(req_valid),
        .req_tag(decoded_tag),
        .req_index(decoded_index),
        .req_offset(decoded_offset),
        .req_ready(req_ready),

        .active_tag(active_tag),
        .active_index(active_index),
        .active_offset(active_offset),

        .lookup_hit(lookup_hit),
        .cache_byte_data(cache_byte_data),
        .refill_byte_data(refill_byte_data),

        .mem_ready(mem_ready),
        .mem_req(mem_req),
        .refill_write_en(refill_write_en),

        .resp_valid(resp_valid),
        .resp_data(resp_data),
        .resp_hit(resp_hit)
    );

    main_memory_model u_main_memory_model (
        .clk(clk),
        .reset(reset),
        .mem_req(mem_req),
        .mem_addr(mem_addr),
        .mem_ready(mem_ready),
        .mem_block(mem_block)
    );

endmodule
